'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const source=fs.readFileSync(path.join(__dirname,'../assets/import-learn.js'),'utf8');
const wait=()=>new Promise(resolve=>setTimeout(resolve,35));
test('approved imported words render compact study cards, with only word audio visible',async()=>{
 const dom=new JSDOM('<!doctype html><html><head></head><body><header></header><div id="p-files"></div><button class="tab" data-p="files"></button></body></html>',{runScripts:'dangerously',pretendToBeVisual:true,url:'https://voclab.website'});
 const {window}=dom;
 window.scrollTo=()=>{};
 const calls=[];
 window.speak=(text,locale)=>calls.push([text,locale]);
 window.fetch=async()=>({ok:true,json:async()=>({words:[{word:'Primarily',type:'adv.',arabic:'بشكل أساسي',english_definition:'Mainly or for the most part.',example:'The building is used primarily for research.',source_excerpt:'Primarily',ipa:'/praɪˈmerəli/'}],file_processing:{document_type:'list'}})});
 window.eval(source);
 const doc=window.document;
 const explain=doc.querySelector('input[name="vocImportIntent"][value="explain"]');
 explain.checked=true;
 explain.dispatchEvent(new window.Event('change',{bubbles:true}));
 const upload=doc.getElementById('vocImportFile');
 Object.defineProperty(upload,'files',{configurable:true,value:[new window.File(['Primarily'],'words.txt',{type:'text/plain'})]});
 doc.getElementById('vocImportAnalyze').click();
 for(let i=0;i<35&&doc.getElementById('p-files').dataset.flowStage!=='review';i++)await wait();
 assert.equal(doc.getElementById('p-files').dataset.flowStage,'review');
 doc.getElementById('vocImportSave').click();
 assert.equal(doc.getElementById('p-files').dataset.flowStage,'practice');
 const card=doc.querySelector('.voc-study-card');
 assert.ok(card);
 assert.equal(card.querySelector('.voc-study-term').textContent,'Primarily');
 assert.equal(card.querySelector('.voc-study-part').textContent,'adv.');
 assert.equal(card.querySelector('.voc-study-arabic').textContent,'بشكل أساسي');
 assert.equal(card.querySelector('.voc-study-definition').textContent,'Mainly or for the most part.');
 const wordButtons=card.querySelectorAll('.voc-study-word-audio button');
 assert.equal(wordButtons.length,2);
 wordButtons[0].click();wordButtons[1].click();
 assert.deepEqual(calls,[['Primarily','en-US'],['Primarily','en-GB']]);
 const details=card.querySelector('.voc-study-example-audio');
 assert.equal(details.open,false,'example pronunciation is collapsed');
 assert.equal(details.querySelectorAll('button').length,2);
 details.open=true;
 details.querySelector('button').click();
 assert.deepEqual(calls[2],['The building is used primarily for research.','en-US']);
 assert.equal(doc.querySelectorAll('.voc-study-card').length,1);
 dom.window.close();
});
